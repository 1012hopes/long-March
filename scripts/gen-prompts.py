def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)


def main():
    n = 0
    for gname, sites in GROUPS:
        for sid, sname, slug, when, scene, note in sites:
            d = os.path.join(PROMPTS, gname, f"{sid} {sname}")
            w(os.path.join(d, "提示词.txt"), HEAD + "\n\n" + scene + "\n")

            corner = "" if sid in INDOOR else " --corner 0 0"
            setup = "出图设置见 prompts/_通用/怎么用.txt\n"
            if sid in SHARED:
                setup = ""
                use = (f"这一站不用另出图 —— 与 {SHARED[sid]} 共用 {slug}360.jpg，"
                       f"只是站的位置和朝向不同。\n")
                cmd = f"  （换图时跟 {SHARED[sid]} 一起换）\n"
            elif sid in OUTNAME:
                out, why = OUTNAME[sid]
                use = f"原图放入 assets/pano-src/{slug}/，成品为 {out}.jpg\n注意：{why}\n"
                cmd = f"  python scripts/prep-pano360.py <源图> {out} --crop 0{corner} --grid\n"
            else:
                use = f"原图放入 assets/pano-src/{slug}/，成品为 {slug}360.jpg\n"
                cmd = f"  python scripts/prep-pano360.py <源图> {slug}360 --crop 0{corner} --grid\n"

            w(os.path.join(d, "备注.txt"),
              f"{sid}  {sname}\n"
              f"时间天气：{when}\n"
              f"{setup}"
              f"{use}"
              f"\n最容易假的地方：\n{note}\n"
              f"\n收拾的时候（我来跑）：\n{cmd}")

            if sid not in SHARED:
                os.makedirs(os.path.join(SRC, slug), exist_ok=True)
            n += 1

    w(os.path.join(PROMPTS, "_通用", "负向提示词.txt"), NEG + "\n")
    w(os.path.join(PROMPTS, "_通用", "怎么用.txt"), HOWTO)

    # 清掉上一版按 node-xx 建的空文件夹
    if os.path.isdir(SRC):
        for name in os.listdir(SRC):
            p = os.path.join(SRC, name)
            if name.startswith("node-") and os.path.isdir(p) and not os.listdir(p):
                os.rmdir(p)
    print("sites:", n)


if __name__ == "__main__":
    main()
